-- Checkout transaction: validates and deducts every SKU, records movements, and
-- inserts the order as one PostgreSQL transaction (all changes roll back on error).
CREATE OR REPLACE FUNCTION create_order_with_inventory(p_order JSONB) RETURNS JSONB LANGUAGE plpgsql AS $$
DECLARE v_item JSONB; v_product products%ROWTYPE; v_qty INTEGER;
BEGIN
  FOR v_item IN SELECT * FROM jsonb_array_elements(p_order->'items') LOOP
    v_qty := (v_item->>'qty')::INTEGER;
    SELECT * INTO v_product FROM products WHERE upper(sku) = upper(v_item->>'sku') FOR UPDATE;
    IF NOT FOUND OR v_qty < 1 OR v_product.stock < v_qty THEN RAISE EXCEPTION 'Insufficient stock for %', v_item->>'sku'; END IF;
    UPDATE products SET stock = stock - v_qty, updated_at = now() WHERE id = v_product.id;
    INSERT INTO inventory_history(product_id, quantity_change, previous_quantity, new_quantity, reason, reference)
    VALUES (v_product.id, -v_qty, v_product.stock, v_product.stock - v_qty, 'Order created', p_order->>'id');
  END LOOP;
  INSERT INTO orders (id, customer_name, email, phone, address, city, total_lkr, status, items, notes, created_at, inventory_deducted)
  VALUES (p_order->>'id', p_order->>'customerName', COALESCE(p_order->>'email',''), p_order->>'phone', COALESCE(p_order->>'address',''), COALESCE(p_order->>'city',''),
    (p_order->>'totalLKR')::INTEGER, p_order->>'status', p_order->'items', COALESCE(p_order->>'notes',''), COALESCE((p_order->>'createdAt')::timestamptz, now()), true);
  RETURN p_order;
END; $$;

CREATE OR REPLACE FUNCTION restore_order_inventory(p_order_id TEXT) RETURNS VOID LANGUAGE plpgsql AS $$
DECLARE v_order orders%ROWTYPE; v_item JSONB; v_product products%ROWTYPE; v_qty INTEGER;
BEGIN
  SELECT * INTO v_order FROM orders WHERE id = p_order_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Order not found'; END IF;
  IF NOT v_order.inventory_deducted OR v_order.inventory_restored THEN RETURN; END IF;
  FOR v_item IN SELECT * FROM jsonb_array_elements(v_order.items) LOOP
    v_qty := (v_item->>'qty')::INTEGER;
    SELECT * INTO v_product FROM products WHERE upper(sku) = upper(v_item->>'sku') FOR UPDATE;
    IF FOUND THEN
      UPDATE products SET stock = stock + v_qty, updated_at = now() WHERE id = v_product.id;
      INSERT INTO inventory_history(product_id, quantity_change, previous_quantity, new_quantity, reason, reference)
      VALUES (v_product.id, v_qty, v_product.stock, v_product.stock + v_qty, 'Order cancelled', v_order.id);
    END IF;
  END LOOP;
  UPDATE orders SET inventory_restored = true, updated_at = now() WHERE id = p_order_id;
END; $$;

