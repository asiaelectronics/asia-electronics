-- Locks the product row, rejects negative stock, updates it and writes one audit entry.
CREATE OR REPLACE FUNCTION adjust_inventory(p_product_id TEXT, p_mode TEXT, p_quantity INTEGER, p_reason TEXT, p_reference TEXT DEFAULT NULL)
RETURNS JSONB LANGUAGE plpgsql AS $$
DECLARE v_product products%ROWTYPE; v_next INTEGER; v_change INTEGER;
BEGIN
  IF p_quantity IS NULL OR p_quantity < 0 THEN RAISE EXCEPTION 'Quantity must be non-negative'; END IF;
  SELECT * INTO v_product FROM products WHERE id = p_product_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Product not found'; END IF;
  IF p_mode = 'add' THEN v_next := v_product.stock + p_quantity;
  ELSIF p_mode = 'remove' THEN v_next := v_product.stock - p_quantity;
  ELSIF p_mode = 'set' THEN v_next := p_quantity;
  ELSE RAISE EXCEPTION 'Invalid inventory adjustment mode'; END IF;
  IF v_next < 0 THEN RAISE EXCEPTION 'Insufficient stock'; END IF;
  v_change := v_next - v_product.stock;
  UPDATE products SET stock = v_next, updated_at = now() WHERE id = p_product_id;
  INSERT INTO inventory_history(product_id, quantity_change, previous_quantity, new_quantity, reason, reference)
  VALUES (p_product_id, v_change, v_product.stock, v_next, COALESCE(p_reason, ''), p_reference);
  RETURN jsonb_build_object('previousQuantity', v_product.stock, 'newQuantity', v_next, 'quantityChange', v_change);
END; $$;

